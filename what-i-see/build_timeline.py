#!/usr/bin/env python3
"""story.js + narration/lines.json  ->  timeline.js

Each scene is stretched by one factor (never squeezed) so every narrated line
fits before the next one starts. Captions, narration clips and sound-effect
cues are moved with their scene. Scenes keep their "base" times, so the
animation code can keep thinking in the original timing.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.abspath(__file__))
LEAD = 0.15   # narration starts this long after its caption appears
GAP = 0.45    # breathing room after a spoken line
SPILL = 0.3   # a scene's last line may run this far into the next scene's transition


def load_js(path, name):
    with open(path, encoding="utf-8") as f:
        return json.loads(re.search(name + r"\s*=\s*(\{.*\})\s*;", f.read(), re.S).group(1))


story = load_js(os.path.join(ROOT, "story.js"), "STORY")
with open(os.path.join(ROOT, "narration", "lines.json"), encoding="utf-8") as f:
    lines = json.load(f)

caps = story["captions"]
for i, c in enumerate(caps):
    c["_i"] = i
    c["_dur"] = lines[str(i)]["dur"] if c.get("say") else 0

scenes = []
t = 0.0
for s in story["scenes"]:
    bs, be = s["start"], s["end"]
    said = sorted([c for c in caps if c.get("say") and bs <= c["t0"] < be], key=lambda c: c["t0"])
    f = 1.0
    for k, c in enumerate(said):
        bound = said[k + 1]["t0"] if k + 1 < len(said) else be + SPILL
        f = max(f, (LEAD + c["_dur"] + GAP) / (bound - c["t0"]))
    f = round(f, 3)
    scenes.append({"id": s["id"], "start": round(t, 3), "end": round(t + (be - bs) * f, 3), "base": [bs, be], "stretch": f})
    t += (be - bs) * f


def warp(x):
    for s in scenes:
        bs, be = s["base"]
        if x < be or s is scenes[-1]:
            return round(s["start"] + (x - bs) * s["stretch"], 3)


out_caps, narration = [], []
for k, c in enumerate(caps):
    t0 = warp(c["t0"])
    t1 = warp(c["t1"])
    if c.get("say"):
        t1 = max(t1, t0 + LEAD + c["_dur"] + 0.6)
        nxt = [warp(d["t0"]) for d in caps[k + 1:] if d.get("say")]
        if nxt:
            t1 = min(t1, nxt[0] - 0.1)
        narration.append({"t": round(t0 + LEAD, 3), "file": "narration/" + lines[str(c["_i"])]["file"], "dur": c["_dur"]})
    cap = {"t0": t0, "t1": round(t1, 3), "text": c["text"], "style": c["style"]}
    out_caps.append(cap)

sfx = []
for e in story["sfx"]:
    e2 = dict(e)
    e2["base"] = e["t"]
    e2["t"] = warp(e["t"])
    sfx.append(e2)

timeline = {
    "title": story["title"],
    "duration": round(warp(story["duration"]), 3),
    "transition": story["transition"],
    "scenes": scenes,
    "captions": out_caps,
    "narration": narration,
    "sfx": sfx,
}
with open(os.path.join(ROOT, "timeline.js"), "w", encoding="utf-8") as f:
    f.write("// GENERATED by build_timeline.py from story.js + narration/lines.json. Do not edit by hand.\n")
    f.write("window.TIMELINE = " + json.dumps(timeline, indent=1, ensure_ascii=True) + ";\n")

for s in scenes:
    print(f"{s['id']:9s} {s['start']:7.2f} -> {s['end']:7.2f}   x{s['stretch']}")
print(f"total {timeline['duration']:.1f}s")
